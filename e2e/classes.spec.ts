import { test, expect } from '@playwright/test';
import { login, uniqueSuffix } from './_helpers';

/**
 * The class creation form has a required "First session" datetime input
 * which we need to fill or the form won't submit. We use a fixed future
 * date well clear of "now" to avoid timezone edge cases on the assertion.
 */
function futureDateTimeLocal(): string {
  const d = new Date();
  d.setDate(d.getDate() + 7);
  d.setHours(18, 0, 0, 0);
  // datetime-local format: YYYY-MM-DDTHH:MM
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(
    d.getHours()
  )}:${pad(d.getMinutes())}`;
}

test.describe('Classes', () => {
  test('create, view, archive, restore', async ({ page }) => {
    await login(page);

    const suffix = uniqueSuffix();
    const title = `Test Class ${suffix}`;

    await page.goto('/classes');
    await page.getByRole('link', { name: /new class/i }).first().click();
    await page.waitForURL(/\/classes\/new/);

    await page.getByLabel(/^title/i).fill(title);
    await page.getByLabel(/description/i).fill('Auto-generated by tests.');
    await page.getByLabel(/instructor/i).fill('Test Instructor');
    await page.getByLabel(/location/i).fill('Test Location');
    await page.getByLabel(/first session/i).fill(futureDateTimeLocal());

    await page.getByRole('button', { name: /create class/i }).click();

    await expect(
      page.getByRole('heading', { name: title })
    ).toBeVisible();
    await expect(page.getByText('Test Instructor')).toBeVisible();

    // Archive — exact-match button name to avoid the "Archived" badge
    await page.getByRole('button', { name: /^archive$/i }).click();
    await expect(page.getByText(/archived/i).first()).toBeVisible();

    // Restore
    await page.getByRole('button', { name: /restore/i }).click();
    await expect(page.getByRole('heading', { name: title })).toBeVisible();
  });

  test('class detail shows calendar subscribe URL', async ({ page }) => {
    await login(page);

    const suffix = uniqueSuffix();
    const title = `Calendar Class ${suffix}`;

    await page.goto('/classes/new');
    await page.getByLabel(/^title/i).fill(title);
    await page.getByLabel(/first session/i).fill(futureDateTimeLocal());
    await page.getByRole('button', { name: /create class/i }).click();

    await expect(page.getByRole('heading', { name: title })).toBeVisible();
    await expect(
      page.getByRole('heading', { name: /subscribable calendar/i })
    ).toBeVisible();

    const code = page.locator('code').filter({ hasText: /\/cal\// }).first();
    await expect(code).toBeVisible();
    await expect(code).toContainText('token=');
  });
});
